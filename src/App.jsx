function AuthScreen(){
  const[mode,setMode]=useState('login');
  const[form,setForm]=useState({email:'',password:''});
  const[err,setErr]=useState('');
  const[ok,setOk]=useState('');
  const[loading,setLoading]=useState(false);
  const set=k=>e=>setForm(f=>({...f,[k]:e.target.value}));
  const inp={padding:'11px 14px',background:C.grayBg,border:`1px solid ${C.border}`,borderRadius:10,color:C.text,fontSize:13,outline:'none',direction:'rtl',width:'100%',boxSizing:'border-box'};

  const MSGS={
    'auth/user-not-found':'البريد غير مسجل',
    'auth/wrong-password':'كلمة المرور خاطئة',
    'auth/invalid-credential':'البريد أو كلمة المرور غير صحيحة',
    'auth/too-many-requests':'محاولات كثيرة — انتظر دقيقة ثم أعد المحاولة',
    'auth/email-already-in-use':'هذا البريد له حساب — استخدم تسجيل الدخول',
    'auth/weak-password':'كلمة المرور ضعيفة (6 أحرف على الأقل)',
    'auth/invalid-email':'صيغة البريد غير صحيحة',
    'auth/network-request-failed':'تعذّر الاتصال بالإنترنت',
  };

  const submit=async()=>{
    if(!form.email.trim()||!form.password){setErr('أدخل البريد وكلمة المرور');return;}
    setLoading(true);setErr('');setOk('');
    const email=form.email.trim().toLowerCase();
    try{
      if(mode==='login')await FB.fbLogin(email,form.password);
      else await FB.fbRegister(email,form.password);
    }catch(e){
      setErr(MSGS[e.code]||'تعذّر إتمام العملية — أعد المحاولة');
      setLoading(false);
    }
  };

  const forgot=async()=>{
    const email=form.email.trim().toLowerCase();
    if(!email){setErr('اكتب بريدك أولًا ثم اضغط "نسيت كلمة المرور"');return;}
    setErr('');setOk('');
    try{
      await FB.resetPassword(email);
      setOk('أُرسل رابط إعادة التعيين إلى بريدك — تحقّق من صندوق الوارد والرسائل المهملة');
    }catch(e){setErr(MSGS[e.code]||'تعذّر الإرسال — تحقّق من البريد');}
  };

  return(
    <div style={{maxWidth:400,margin:'30px auto',padding:'0 16px',direction:'rtl'}}>
      <div style={{background:C.white,border:`1px solid ${C.border}`,borderRadius:20,padding:'26px 20px',boxShadow:'0 4px 20px rgba(0,0,0,.07)'}}>
        <div style={{textAlign:'center',marginBottom:20}}>
          <img src={LOGO} alt="" style={{height:48,marginBottom:7}}/>
          <div style={{color:C.teal,fontWeight:800,fontSize:15}}>سباق القرّاء الصيفي 1</div>
        </div>
        <div style={{display:'flex',borderRadius:10,overflow:'hidden',border:`1px solid ${C.border}`,marginBottom:16}}>
          {[['login','تسجيل الدخول'],['register','إنشاء حساب']].map(([m,l])=>(
            <button key={m} onClick={()=>{setMode(m);setErr('');setOk('');}} style={{flex:1,padding:'10px',background:mode===m?C.teal:C.white,color:mode===m?C.white:C.gray,border:'none',cursor:'pointer',fontSize:12,fontWeight:700}}>{l}</button>
          ))}
        </div>
        <div style={{display:'flex',flexDirection:'column',gap:10}}>
          <input type="email" placeholder="البريد الإلكتروني *" value={form.email} onChange={set('email')} style={inp}/>
          <input type="password" placeholder="كلمة المرور *" value={form.password} onChange={set('password')} onKeyDown={e=>e.key==='Enter'&&submit()} style={inp}/>
          {err&&<div style={{background:C.redBg,color:C.red,fontSize:12,padding:'8px 12px',borderRadius:8,textAlign:'center',lineHeight:1.7}}>{err}</div>}
          {ok&&<div style={{background:C.greenBg,color:C.green,fontSize:12,padding:'8px 12px',borderRadius:8,textAlign:'center',lineHeight:1.7}}>{ok}</div>}
          <button onClick={submit} disabled={loading} style={{padding:12,background:loading?C.grayL:C.teal,color:C.white,border:'none',borderRadius:10,fontSize:14,fontWeight:800,cursor:loading?'not-allowed':'pointer',marginTop:2}}>
            {loading?'جارٍ...':(mode==='login'?'دخول':'إنشاء الحساب')}
          </button>
          {mode==='login'&&(
            <button onClick={forgot} style={{background:'transparent',border:'none',color:C.teal,fontSize:11.5,fontWeight:700,cursor:'pointer',padding:4}}>نسيت كلمة المرور؟</button>
          )}
        </div>
        {mode==='register'&&<div style={{color:C.muted,fontSize:10.5,textAlign:'center',marginTop:10,lineHeight:1.7}}>ستختار اسمك من قائمة الحلقات بعد إنشاء الحساب</div>}
      </div>
    </div>
  );
}

