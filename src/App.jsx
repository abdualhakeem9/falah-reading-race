function getActiveHeat(){
  const n=Date.now();
  for(const h of HEATS){if(n>=h.start&&n<=h.end)return{heat:h,status:'active'};}
  for(const h of HEATS){if(n<h.start)return{heat:h,status:'upcoming'};}
  return{heat:HEATS[2],status:'done'};
}
function getHeatStatus(h){const n=Date.now();if(n<h.start)return'upcoming';if(n>h.end)return'done';return'active';}
const dayKey=()=>new Date().toISOString().slice(0,10);
const arDays=n=>n===1?'يوم':n===2?'يومان':n<=10?`${n} أيام`:`${n} يومًا`;

// دمج قائمة الأسماء المعتمدة مع الحسابات المسجّلة
function mergeRoster(registered){
  if(!SHOW_ALL_ROSTER)return registered;
  const byName={};
  registered.forEach(s=>{if(s.name)byName[s.name]=s;});
  const all=ROSTER.map(r=>byName[r.n]||{id:'r_'+r.n,name:r.n,group:r.g,km:0,ghost:true});
  registered.forEach(s=>{if(s.name&&!ROSTER.some(r=>r.n===s.name))all.push(s);});
  return all.sort((a,b)=>(b.km||0)-(a.km||0));
}

// الأسماء المتاحة للاختيار (غير المحجوزة)
function availableNames(registered){
  const taken=new Set(registered.map(s=>s.name).filter(Boolean));
  return ROSTER.filter(r=>!taken.has(r.n));
}

// اختيار يومي ثابت (يتغيّر كل يوم، ولا يتغيّر خلال اليوم)
function dailyPick(arr,count){
  if(!arr.length)return[];
  const seed=[...dayKey()].reduce((a,c)=>a+c.charCodeAt(0),0);
  const idx=arr.map((_,i)=>i).sort((a,b)=>(((a+1)*seed)%97)-(((b+1)*seed)%97));
  return idx.slice(0,count).map(i=>arr[i]);
}

// توليد أخبار السباق تلقائياً
function generateNews(students,benefits){
  const news=[];
  const{heat,status}=getActiveHeat();
  const totalKm=students.reduce((a,s)=>a+(s.km||0),0);
  const movers=students.filter(s=>(s.km||0)>0);

  if(status==='active'){
    const left=Math.max(1,Math.ceil((heat.end-Date.now())/864e5));
    news.push({i:heat.emoji,t:`مرحلة ${heat.name} جارية — باقٍ ${arDays(left)}`,k:'hot'});
    const pct=Math.min(100,Math.round(totalKm/heat.target*100));
    news.push({i:'🎯',t:pct>=100?`تجاوزنا هدف المرحلة (${heat.target} كم) 🎉`:`بلغنا ${pct}% من هدف المرحلة (${heat.target} كم)`});
  }else if(status==='upcoming'){
    const d=Math.max(1,Math.ceil((heat.start-Date.now())/864e5));
    news.push({i:'⏳',t:`تنطلق مرحلة ${heat.name} بعد ${arDays(d)} — استعدّوا`,k:'hot'});
  }else{
    news.push({i:'🏁',t:'انتهى السباق — بارك الله في جهودكم'});
  }

  const gk=GROUPS.map(g=>({g,km:students.filter(s=>s.group===g).reduce((a,s)=>a+(s.km||0),0)})).sort((a,b)=>b.km-a.km);
  if(gk[0]&&gk[0].km>0){
    news.push({i:'🏆',t:`${gk[0].g} تتصدّر الحلقات بـ${gk[0].km} كم`,k:'gold'});
    if(gk[1]&&gk[1].km>0){
      const d=gk[0].km-gk[1].km;
      news.push({i:'⚔️',t:d===0?`تعادل مثير بين ${gk[0].g} و${gk[1].g}`:`${gk[1].g} تلاحق المتصدّرة بفارق ${d} كم فقط`});
    }
  }
  if(movers.length){
    news.push({i:'🥇',t:`${movers[0].name} يتصدّر الفرسان بـ${movers[0].km} كم`,k:'gold'});
    if(movers[1]){const d=(movers[0].km||0)-(movers[1].km||0);
      if(d<=20)news.push({i:'🔥',t:`منافسة محتدمة — ${movers[1].name} على بُعد ${d} كم من الصدارة`,k:'hot'});}
  }
  if(totalKm>0)news.push({i:'📏',t:`قطع الفرسان ${totalKm} كم مجتمعين`});
  const tips=[
    {i:'🧭',t:'صفحة من الكتب المقترحة تساوي صفحة ونصفًا من غيرها'},
    {i:'🏹',t:'الفارس الذكي لا يقرأ أكثر فحسب، بل يختار ما يقرّبه أسرع'},
  ];
  news.push(tips[new Date().getDate()%tips.length]);
  news.push({i:'🏃',t:`${movers.length} من ${ROSTER.length} فارسًا انطلقوا في الميدان`});
  if(benefits.length)news.push({i:'💡',t:`${benefits.length} فائدة سجّلها الفرسان حتى الآن`});
  if(totalKm===0)news.push({i:'🚀',t:'الميدان مفتوح — سجّل أول قراءة واكسب الصدارة',k:'hot'});
  return news;
}

function useCountdownTo(target){
  const[t,setT]=useState({d:0,h:0,m:0,s:0});
  useEffect(()=>{
    if(!target)return;
    const f=()=>{const diff=target-Date.now();if(diff<=0)return;setT({d:Math.floor(diff/864e5),h:Math.floor((diff%864e5)/36e5),m:Math.floor((diff%36e5)/6e4),s:Math.floor((diff%6e4)/1e3)});};
    f();const id=setInterval(f,1000);return()=>clearInterval(id);
  },[target]);
  return t;
}
function useTick(ms=1000){const[t,setT]=useState(0);useEffect(()=>{const id=setInterval(()=>setT(x=>x+1),ms);return()=>clearInterval(id);},[]);return t;}

